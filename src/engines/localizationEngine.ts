export class LocalizationEngine {
  private static currentLang: SupportedLanguage = 'es';
  private static currentCurrency: CurrencyCode = 'USD';

  public static setLanguage(lang: SupportedLanguage): void {
    this.currentLang = lang;
  }

  public static getLanguage(): SupportedLanguage {
    return this.currentLang;
  }

  public static getCurrentLanguage(): SupportedLanguage {
    return this.currentLang;
  }

  public static setCurrency(curr: CurrencyCode): void {
    this.currentCurrency = curr;
  }

  public static getCurrency(): CurrencyCode {
    return this.currentCurrency;
  }

  public static getCurrentCurrency(): CurrencyCode {
    return this.currentCurrency;
  }

  public static t(key?: keyof TranslationDictionary | string): any {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.es;
    if (!key) return dict;

    // Support dot notation (e.g. 'nav.overview', 'epistemic.ruleOfGold')
    if (typeof key === 'string') {
      if (key in dict) {
        return (dict as any)[key];
      }

      const keyMapping: Record<string, string> = {
        'nav.overview': dict.tabOverview,
        'nav.indicators': dict.tabIndicators,
        'nav.aiImpact': dict.tabAiImpact,
        'nav.causalLab': dict.tabCausalLab,
        'nav.digitalTwin': dict.tabDigitalTwin,
        'nav.predictive': dict.tabPredictive,
        'nav.fulgorIndex': dict.tabFulgorIndex,
        'nav.ecosystem': dict.tabEcosystem,
        'nav.alerts': dict.tabAlerts,
        'copilot.title': dict.copilot,
        'reports.title': dict.exportReport,
        'epistemic.ruleOfGold': dict.ruleOfGoldSubtitle,
      };

      if (keyMapping[key]) {
        return keyMapping[key];
      }
    }

    return (dict as any)[key] || key;
  }

  public static formatNumber(val: number, decimals: number = 2): string {
    const locale = this.getLocaleCode();
    return new Intl.NumberFormat(locale, {
      minimumFractionDigits: decimals,
      maximumFractionDigits: decimals,
    }).format(val);
  }

  public static formatCurrency(val: number, currency: CurrencyCode = this.currentCurrency): string {
    const locale = this.getLocaleCode();
    return new Intl.NumberFormat(locale, {
      style: 'currency',
      currency: currency,
      maximumFractionDigits: 1,
    }).format(val);
  }

  public static formatPercent(val: number, decimals: number = 1): string {
    const sign = val > 0 ? '+' : '';
    return `${sign}${val.toFixed(decimals)}%`;
  }

  public static formatDate(dateStr: string): string {
    try {
      const date = new Date(dateStr);
      if (isNaN(date.getTime())) return dateStr;
      return date.toLocaleDateString(this.getLocaleCode(), {
        year: 'numeric',
        month: 'short',
        day: 'numeric',
      });
    } catch {
      return dateStr;
    }
  }

  private static getLocaleCode(): string {
    switch (this.currentLang) {
      case 'en': return 'en-US';
      case 'pt': return 'pt-BR';
      case 'fr': return 'fr-FR';
      case 'de': return 'de-DE';
      case 'it': return 'it-IT';
      case 'zh': return 'zh-CN';
      case 'ja': return 'ja-JP';
      default: return 'es-MX';
    }
  }
}
